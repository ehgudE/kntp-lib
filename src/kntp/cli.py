"""Command line interface: ``kntp`` / ``python -m kntp``."""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from collections.abc import Sequence

from . import __version__
from .core import (
    DEFAULT_BASE,
    DEFAULT_MONITOR_INTERVAL,
    DEFAULT_SERVERS,
    MAX_RECOMMEND_COUNT,
    OFFSET_METHODS,
    Ranked,
    Stats,
    collect_stats,
    format_ranked_table,
    monitor,
    rank_servers,
    recommend_set,
)

FORMATS = ("table", "chrony", "w32tm", "json")

# 설정 파일·명령에 그대로 들어가므로 호스트 이름/IP 주소에 쓰는 문자만 허용한다.
# 한글 도메인 같은 IDN은 punycode(xn--...)로 넣으면 된다.
_HOST_RE = re.compile(r"^[A-Za-z0-9._:\-]+$")


def _host(value: str) -> str:
    value = value.strip()
    if not value or len(value) > 253 or not _HOST_RE.fullmatch(value):
        raise argparse.ArgumentTypeError(f"invalid server name: {value!r}")
    return value


_DURATION_RE = re.compile(r"^(\d+(?:\.\d+)?)([smhd]?)$")
_UNIT_SECONDS = {"": 1, "s": 1, "m": 60, "h": 3600, "d": 86400}


def parse_duration(value: str) -> float:
    """'90', '90s', '30m', '4h', '1d', '1.5h' 형식의 기간을 초로 바꾼다."""
    match = _DURATION_RE.fullmatch(value.strip().lower())
    if not match:
        raise argparse.ArgumentTypeError(
            f"invalid duration: {value!r} (examples: 30m, 4h, 1d)"
        )
    seconds = float(match.group(1)) * _UNIT_SECONDS[match.group(2)]
    if seconds <= 0:
        raise argparse.ArgumentTypeError("duration must be greater than 0")
    return seconds


def _human(seconds: float) -> str:
    seconds = int(round(seconds))
    hours, rest = divmod(seconds, 3600)
    minutes, secs = divmod(rest, 60)
    if hours:
        return f"{hours}시간 {minutes}분"
    if minutes:
        return f"{minutes}분 {secs}초"
    return f"{secs}초"


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="kntp",
        description=(
            "KRISS(ntp.kriss.re.kr)를 기준으로 NTP 서버를 측정하고, "
            "함께 쓸 보조 NTP 서버를 추천합니다."
        ),
    )
    parser.add_argument("servers", nargs="*", type=_host, metavar="SERVER",
                        help="측정할 서버 (생략하면 기본 서버 목록)")
    parser.add_argument("--base", type=_host, default=DEFAULT_BASE,
                        help=f"기준 서버 (기본값: {DEFAULT_BASE})")
    parser.add_argument("-n", "--samples", type=int, default=7, help="서버당 측정 횟수 (기본값: 7)")
    parser.add_argument("--timeout", type=float, default=2.0, help="응답 대기 시간(초) (기본값: 2.0)")
    parser.add_argument("--sleep", type=float, default=0.3, dest="sleep_between",
                        help="측정 회차 사이 대기 시간(초) (기본값: 0.3)")
    parser.add_argument("-w", "--watch", type=parse_duration, metavar="DURATION",
                        help="장기 측정 모드: 이 기간 동안 일정 간격으로 측정 (예: 30m, 4h, 1d). "
                             "Ctrl+C로 중간에 멈추면 그때까지의 결과로 추천")
    parser.add_argument("--interval", type=float, default=DEFAULT_MONITOR_INTERVAL,
                        help=f"장기 측정 모드의 측정 간격(초), 16-3600 "
                             f"(기본값: {DEFAULT_MONITOR_INTERVAL:g})")
    parser.add_argument("-c", "--count", type=int, default=3,
                        help=f"추천할 보조 서버 수, 1-{MAX_RECOMMEND_COUNT} (기본값: 3)")
    parser.add_argument("--offset-method", choices=OFFSET_METHODS, default="mean",
                        help="기준 서버와 비교할 offset (기본값: mean)")
    parser.add_argument("--max-delay", type=float, default=100.0,
                        help="이 delay(ms) 이상인 서버는 제외 (기본값: 100)")
    parser.add_argument("--require-ok-rate", type=float, default=0.8,
                        help="추천에 필요한 최소 성공률 (기본값: 0.8)")
    parser.add_argument("-f", "--format", choices=FORMATS, default="table",
                        help="출력 형식: table(기본), chrony(chrony.conf 설정), "
                             "w32tm(Windows 명령), json")
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    return parser


def _is_pool(host: str) -> bool:
    return host == "pool.ntp.org" or host.endswith(".pool.ntp.org")


def format_chrony(base: str, picked: Sequence[Ranked]) -> str:
    """chrony.conf에 넣을 서버 설정 줄."""
    lines = [f"# Generated by kntp {__version__} (base: {base})"]
    for host in [base, *(item.server for item in picked)]:
        directive = "pool" if _is_pool(host) else "server"
        suffix = " prefer" if host == base else ""
        lines.append(f"{directive} {host} iburst{suffix}")
    return "\n".join(lines)


def format_w32tm(base: str, picked: Sequence[Ranked]) -> str:
    """Windows 시간 서비스 설정 명령(관리자 권한 명령 프롬프트에서 실행)."""
    peers = " ".join(f"{host},0x8" for host in [base, *(item.server for item in picked)])
    return "\n".join([
        f'w32tm /config /manualpeerlist:"{peers}" /syncfromflags:manual /update',
        "w32tm /resync /rediscover",
    ])


def _to_dict(item: Ranked) -> dict:
    return {
        "server": item.server,
        "score": item.score,
        "grade": item.grade,
        "vs_base_ms": item.vs_base_ms,
        "uncertainty_ms": item.uncertainty_ms,
        "avg_offset_ms": item.avg_offset_ms,
        "std_offset_ms": item.std_offset_ms,
        "avg_delay_ms": item.avg_delay_ms,
        "std_delay_ms": item.std_delay_ms,
        "ok": item.ok,
        "fail": item.fail,
    }


def format_report(base: str, ranked: Sequence[Ranked], picked: Sequence[Ranked]) -> str:
    lines = [format_ranked_table(list(ranked), top_n=None), ""]
    lines.append("± : 경로 비대칭으로 생길 수 있는 최대 오차입니다. "
                 "|vs_base|가 ±보다 작으면 기준 서버와의 차이를 측정으로 구분할 수 없습니다.")
    lines.append("")
    if picked:
        lines.append(f"추천 보조 서버 (기준 {base}와 함께 사용):")
        for index, item in enumerate(picked, start=1):
            lines.append(
                f"  {index}. {item.server}  [{item.grade}] "
                f"vs_base {item.vs_base_ms:+.2f} ms ± {item.uncertainty_ms:.2f} ms, "
                f"delay {item.avg_delay_ms:.2f} ms"
            )
    else:
        lines.append("조건을 만족하는 보조 서버가 없습니다.")
    return "\n".join(lines)


def _watch(servers: list[str], args: argparse.Namespace) -> tuple[list[Stats], int]:
    """장기 측정을 실행한다. Ctrl+C로 멈추면 마지막으로 끝난 회차까지의 통계를 쓴다."""
    rounds = max(1, math.ceil(args.watch / args.interval))
    count = len(dict.fromkeys(servers))
    print(
        f"장기 측정 시작: 서버 {count}개, {args.interval:g}초 간격 {rounds}회 "
        f"(약 {_human((rounds - 1) * args.interval)}). Ctrl+C로 중간에 멈출 수 있습니다.",
        file=sys.stderr,
    )
    latest: list[tuple[int, list[Stats]]] = []

    def on_round(done: int, total: int, stats: list[Stats]) -> None:
        latest[:] = [(done, stats)]
        remaining = (total - done) * args.interval
        print(f"[{done}/{total}] 응답한 서버 {len(stats)}개, 남은 시간 약 {_human(remaining)}",
              file=sys.stderr, flush=True)

    try:
        stats = monitor(servers, rounds=rounds, interval=args.interval, timeout=args.timeout,
                        on_round=on_round)
        return stats, rounds
    except KeyboardInterrupt:
        if not latest:
            raise RuntimeError("측정이 끝나기 전에 중단되었습니다 (완료된 회차 없음).") from None
        done, stats = latest[0]
        print(f"중단됨: {done}회차까지의 결과로 계산합니다.", file=sys.stderr)
        return stats, done


def main(argv: Sequence[str] | None = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)

    servers = list(args.servers) or list(DEFAULT_SERVERS)
    if args.base not in servers:
        servers.insert(0, args.base)

    rounds_done: int | None = None
    try:
        if not 1 <= args.count <= MAX_RECOMMEND_COUNT:
            raise ValueError(f"--count must be between 1 and {MAX_RECOMMEND_COUNT}")
        if args.watch is None:
            print(f"측정 중: 서버 {len(dict.fromkeys(servers))}개 x {args.samples}회 ...",
                  file=sys.stderr)
            stats = collect_stats(servers, samples=args.samples, timeout=args.timeout,
                                  sleep_between=args.sleep_between)
        else:
            stats, rounds_done = _watch(servers, args)
        ranked = rank_servers(stats, base=args.base, max_delay_ms=args.max_delay,
                              offset_method=args.offset_method)
        picked = recommend_set(ranked, count=args.count, require_ok_rate=args.require_ok_rate)
    except ValueError as exc:
        parser.error(str(exc))  # exit code 2
    except RuntimeError as exc:
        print(f"kntp: error: {exc}", file=sys.stderr)
        return 1

    if args.format == "json":
        output = json.dumps(
            {
                "version": __version__,
                "mode": "watch" if args.watch is not None else "quick",
                "rounds": rounds_done,
                "base": args.base,
                "offset_method": args.offset_method,
                "ranked": [_to_dict(item) for item in ranked],
                "recommended": [item.server for item in picked],
            },
            ensure_ascii=False,
            indent=2,
        )
    elif args.format == "chrony":
        output = format_chrony(args.base, picked)
    elif args.format == "w32tm":
        output = format_w32tm(args.base, picked)
    else:
        output = format_report(args.base, ranked, picked)
    print(output)

    if not picked:
        if args.format != "table":
            print("kntp: warning: no secondary server met the conditions", file=sys.stderr)
        return 1
    return 0
